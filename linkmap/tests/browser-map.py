# Optional browser check: python tests/browser-map.py (requires Playwright and Chromium).
import functools, http.server, os, pathlib, shutil, threading
from playwright.sync_api import sync_playwright, expect
LINKMAP = pathlib.Path(__file__).resolve().parents[1]
ROOT = LINKMAP.parent
(ROOT / 'work').mkdir(exist_ok=True)
class Quiet(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *args): pass
handler = functools.partial(Quiet, directory=str(ROOT))
server = http.server.ThreadingHTTPServer(('127.0.0.1', 0), handler)
threading.Thread(target=server.serve_forever, daemon=True).start()
origin = f'http://127.0.0.1:{server.server_port}'
checks = 0
def check(value, message):
    global checks
    assert value, message
    checks += 1
    if os.environ.get('LINKMAP_BROWSER_VERBOSE'):
        print(f'Passed: {message}', flush=True)
with sync_playwright() as pw:
    executable = os.environ.get('LINKMAP_CHROMIUM') or shutil.which('chromium') or shutil.which('google-chrome')
    browser = pw.chromium.launch(executable_path=executable, headless=True, args=['--no-sandbox'])
    page = browser.new_page(viewport={'width':1440,'height':1000})
    errors=[]
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.add_init_script(path=str(LINKMAP/'tests/fixtures/map-sdk.js'))
    def route(request):
        if 'cdn.apple-mapkit.com' in request.request.url:
            request.fulfill(content_type='application/javascript', body='window.initMapKit();')
        elif request.request.url.startswith(origin): request.continue_()
        else: request.fulfill(content_type='application/javascript', body='')
    page.route('**/*', route)
    page.goto(origin+'/linkmap/app/')
    page.wait_for_function("document.getElementById('project-status').textContent.includes('Location')")
    check(not errors, 'no startup page errors')
    check(page.locator('#search-toggle').is_visible() and page.locator('#projects-toggle').is_visible(), 'Search and Projects are persistent sidebar buttons')
    check(page.locator('#search-panel').is_visible() and not page.locator('#projects-panel').is_visible(), 'desktop starts with one Search panel')
    page.locator('#projects-toggle').click()
    check(page.locator('#projects-panel').is_visible() and not page.locator('#search-panel').is_visible(), 'Projects replaces Search in the sidebar')
    check(page.locator('#projects-toggle').get_attribute('aria-expanded')=='true' and page.locator('#search-toggle').get_attribute('aria-expanded')=='false', 'sidebar buttons expose their active state')
    check(page.locator('#project-list button').count()==2, 'project sidebar contains all projects')
    check(page.evaluate("window.__test.maps[0].annotations.length")==3, 'only valid map coordinates are plotted')
    check(page.evaluate("window.__test.maps[0].overlays.length")==1, 'layer convex hull rendered from saved vertices')
    check(page.evaluate("window.__test.maps[0].options.selectableMapFeatures.length")==3, 'Apple map features enabled for selection')
    check(page.evaluate("window.__test.maps[0].options.selectableMapFeatureSelectionAccessory.options.style")=='callout', 'Apple map features use native callout accessory')
    check('1 without valid coordinates' in page.locator('#project-status').inner_text(), 'invalid coordinate record is explained')
    query_count=page.evaluate('window.__test.queries.length')
    page.locator('#project-refresh').click()
    expect(page.locator('#project-refresh')).to_be_enabled()
    check(page.evaluate('window.__test.queries.length')==query_count+4, 'Refresh map data reloads the four collections for the selected project')
    page.locator('#project-filter').fill('Beta')
    check(page.locator('#project-list button').count()==1, 'sidebar filters projects')
    page.locator('#project-filter').fill('')
    page.locator('#project-console').click()
    expect(page.locator('#record-console')).to_be_visible()
    page.locator('#console-content').get_by_role('button',name='Items · 1',exact=True).press('Enter')
    expect(page.locator('#console-title')).to_be_focused()
    page.locator('#console-content').get_by_role('button',name='Water bottle',exact=True).press('Enter')
    check(page.locator('#console-title').inner_text()=='Water bottle', 'Item saved name available through project console')
    check(page.locator('#console-content input').count()==0, 'Item view contains no editor')
    expect(page.locator('#console-title')).to_be_focused()
    page.locator('#console-back').press('Enter')
    expect(page.locator('#console-title')).to_be_focused()
    check(page.locator('#console-title').inner_text()=='Items', 'keyboard Back returns to the related record list')
    page.locator('#console-back').press('Enter')
    expect(page.locator('#console-title')).to_be_focused()
    check(not page.locator('#console-back').is_visible() and page.locator('#console-title').inner_text()=='Alpha Project', 'keyboard focus stays on visible details when Back becomes hidden')
    page.locator('#locations-console').click()
    page.locator('#console-content').get_by_role('button',name='Missing Coordinate',exact=True).click()
    check('no valid map coordinate' in page.locator('#console-content').inner_text(), 'unplottable Location remains viewable')
    check(page.locator('#console-content a').count()==0, 'invalid coordinate does not produce Directions link')
    page.locator('#console-close').click()
    page.locator('#search-toggle').click()
    page.locator('#record-query').fill('accessible building')
    expect(page.locator('#record-results button')).to_have_count(1)
    page.locator('#record-query').press('ArrowDown')
    page.keyboard.press('Enter')
    check(page.locator('#console-title').inner_text()=='Entrance', 'record search keyboard navigation opens matching Location')
    check('An accessible entrance' in page.locator('#console-content').inner_text(), 'native description displayed in About')
    check('Building' in page.locator('#console-content').inner_text() and 'First Floor' in page.locator('#console-content').inner_text(), 'Location Region and Layer context displayed')
    fields=page.locator('#console-content').evaluate("node => Object.fromEntries([...node.querySelectorAll('dt')].map(label => [label.textContent, label.nextElementSibling.textContent]))")
    check(fields=={'Project':'Alpha Project','Latitude':'1.1','Longitude':'1.1','Area vertices':'3'}, 'Location details show the saved project, coordinates and area vertex count')
    check(page.locator('#console-content a').get_attribute('href').startswith('https://maps.apple.com/?daddr='), 'Directions opens viewing navigation')
    check(page.evaluate("window.__test.maps[0].overlays.length")==2, 'selected Location saved area rendered separately')
    check(page.evaluate("window.__test.maps[0].annotations.find(a=>a.title==='Roof').glyphText")=='↑2', 'layer accessory distinguishes higher level')
    detail_box=page.locator('#record-console').bounding_box()
    map_box=page.locator('#map').bounding_box()
    check(detail_box['x']+detail_box['width']<=map_box['x']+1, 'desktop Location details sit beside the map without covering it')
    check(map_box['width']>=500 and map_box['height']>=600, 'desktop Location details leave a usable map')
    page.screenshot(path=str(ROOT/'work/map-desktop.png'),full_page=True)
    page.set_viewport_size({'width':1024,'height':768})
    detail_box=page.locator('#record-console').bounding_box()
    map_box=page.locator('#map').bounding_box()
    check(detail_box['x']+detail_box['width']<=map_box['x']+1 and map_box['width']>=400, 'tablet Location panel retains an uncovered map')
    check(page.evaluate('document.documentElement.scrollWidth <= window.innerWidth'), 'tablet details have no horizontal overflow')
    page.screenshot(path=str(ROOT/'work/map-tablet.png'),full_page=True)
    page.set_viewport_size({'width':1440,'height':1000})
    page.locator('#projects-toggle').click()
    page.locator('#regions-console').click()
    page.locator('#console-content').get_by_role('button',name='Building',exact=True).click()
    buttons=page.locator('#console-content button').all_text_contents()
    check(buttons==['Locations · 3','Roof Level · Level 2','First Floor · Level 1','Map · Level 0'], 'Region console layers ordered like native with Map base')
    page.locator('#console-content').get_by_role('button',name='First Floor · Level 1',exact=True).click()
    check('Locations' in page.locator('#console-content').inner_text(), 'Layer console shows associated Locations')
    check(page.evaluate("window.__test.maps[0].annotations.length")==3, 'layer selection retains every level and unlayered Location in Region')
    page.locator('#layer-select').select_option('')
    check(page.locator('#map-context').inner_text()=='Building · Map · Level 0', 'Map level preserves focused Region')
    page.locator('#map-show-all').click()
    check(page.evaluate("window.__test.maps[0].annotations.length")==3, 'Show all returns project map')
    page.evaluate("window.__test.maps[0].selectAnnotation(window.__test.maps[0].annotations.find(a=>a.title==='Roof'))")
    check(page.locator('#console-title').inner_text()=='Roof', 'map marker replaces current console detail')
    page.locator('#console-close').press('Escape')
    expect(page.locator('#record-console')).not_to_be_visible()
    page.locator('#project-console').click()
    page.evaluate("window.__test.maps[0].selectAnnotation(new mapkit.MapFeatureAnnotation('Old POI'));window.__test.maps[0].selectAnnotation(new mapkit.MapFeatureAnnotation('New POI'))")
    page.evaluate("window.__test.lookups[1].resolve({name:'New POI',coordinate:{latitude:5,longitude:6}})")
    expect(page.locator('#place-detail')).to_contain_text('Apple place details: New POI')
    check(page.locator('#search-panel').is_visible() and not page.locator('#record-console').is_visible(), 'Apple place selection reveals Search and dismisses project details')
    page.evaluate("window.__test.lookups[0].resolve({name:'Old POI',coordinate:{latitude:7,longitude:8}})")
    check('New POI' in page.locator('#place-detail').inner_text(), 'late Apple POI lookup cannot replace current details')
    page.evaluate("window.__test.maps[0].selectAnnotation(new mapkit.MapFeatureAnnotation('Deselected POI'));window.__test.maps[0].emit('deselect');window.__test.lookups[2].resolve({name:'Deselected POI'})")
    check('New POI' in page.locator('#place-detail').inner_text(), 'deselected Apple POI cannot reopen details')
    page.locator('#place-query').fill('Cafe')
    expect(page.locator('#place-results button')).to_have_count(1)
    page.locator('#place-results button').click()
    expect(page.locator('#place-detail')).to_contain_text('Apple place details: Cafe')
    check(page.locator('#place-results').is_hidden(), 'autocomplete suggestion resolves directly to selected place')
    check(page.locator('#coordinate-input').input_value()=='3, 4', 'place selection updates coordinates')
    page.locator('#coordinate-input').fill('91, 0')
    page.locator('#coordinate-show').click()
    check(page.locator('#coordinate-input').get_attribute('aria-invalid')=='true', 'coordinate input rejects latitude outside range')
    page.locator('#coordinate-input').fill('0, 0')
    page.locator('#coordinate-show').click()
    check(page.evaluate("window.__test.maps[0].region.center.latitude")==0, 'explicit origin coordinates inspectable')
    page.locator('#projects-toggle').click()
    page.locator('[data-project-id="p2"]').click()
    page.wait_for_function("document.getElementById('project-status').textContent.startsWith('1 Location')")
    check(page.evaluate("window.__test.maps[0].overlays.length")==0, 'project switching removes previous vertices and hulls')
    check(page.evaluate("window.__test.maps[0].annotations.map(a=>a.title)")==['Selected coordinate','Beta Place'], 'project switching replaces markers and retains independent coordinate')
    check(page.locator('#record-query').input_value()=='', 'project switching clears old search')
    page.evaluate("window.__test.delays={p1:250,p2:10}")
    page.locator('[data-project-id="p1"]').click()
    page.locator('[data-project-id="p2"]').click()
    page.wait_for_timeout(350)
    check(page.evaluate("window.__test.maps[0].annotations.map(a=>a.title)")==['Selected coordinate','Beta Place'], 'late collection responses cannot mix projects')
    page.locator('[data-project-id="p1"]').click()
    page.evaluate("window.__test.auth('signed-out')")
    page.wait_for_timeout(350)
    check(page.locator('#project-sign-in').is_visible() and page.locator('#record-query').is_disabled(), 'sign-out clears view controls and reveals sign in')
    check(page.evaluate("window.__test.maps[0].annotations.map(a=>a.title)")==['Selected coordinate'], 'sign-out cancels pending project graphics')
    page.locator('#search-toggle').click()
    page.locator('#place-query').fill('Public park')
    page.locator('#place-search-submit').click()
    expect(page.locator('#place-results button')).to_have_count(1)
    check(not page.locator('#place-query').is_disabled(), 'Apple place search remains available signed out')
    page.evaluate("window.__test.delays={};window.__test.auth('signed-in')")
    page.wait_for_function("document.getElementById('project-status').textContent.startsWith('3 Locations')")
    page.set_viewport_size({'width':390,'height':844})
    check(page.locator('#projects-toggle').is_visible() and page.locator('#search-toggle').is_visible(), 'mobile keeps Search and Projects available')
    check(not page.locator('#projects-panel').is_visible() and not page.locator('#search-panel').is_visible(), 'mobile sidebar starts collapsed to show the map')
    page.locator('#search-toggle').click()
    check(page.locator('#search-panel').is_visible(), 'mobile Search button reveals the search panel')
    page.locator('#place-query').press('Escape')
    check(not page.locator('#search-panel').is_visible(), 'Escape dismisses the mobile sidebar panel')
    check(page.locator('#search-toggle').evaluate('(node)=>node===document.activeElement'), 'Escape restores focus to the Search button')
    page.locator('#projects-toggle').click()
    check(page.locator('#projects-panel').is_visible(), 'mobile Projects toggle opens sidebar')
    page.locator('[data-project-id="p2"]').click()
    page.wait_for_function("document.getElementById('project-status').textContent.startsWith('1 Location')")
    check(not page.locator('#projects-panel').is_visible(), 'mobile project choice closes sidebar')
    check(page.locator('#projects-toggle').evaluate('(node)=>node===document.activeElement'), 'mobile project choice returns keyboard focus to visible toggle')
    page.locator('#projects-toggle').click()
    page.locator('#locations-console').click()
    page.locator('#console-content').get_by_role('button',name='Beta Place',exact=True).click()
    check(page.locator('#console-title').inner_text()=='Beta Place', 'console works on mobile')
    check(page.evaluate('document.documentElement.scrollWidth <= window.innerWidth'), 'mobile layout has no horizontal overflow')
    check(page.locator('#map').bounding_box()['height']>=180, 'mobile map keeps usable height')
    map_box=page.locator('#map').bounding_box()
    sheet_box=page.locator('#record-console').bounding_box()
    check(sheet_box['y']-map_box['y']>=120, 'mobile map remains visible above modeless console')
    page.mouse.click(map_box['x']+map_box['width']/2,map_box['y']+140)
    check(page.evaluate('window.__test.mapClicks')>0, 'map remains interactive while console is open')
    check(page.locator('#console-content input, #console-content textarea').count()==0, 'record console exposes viewing controls only')
    page.screenshot(path=str(ROOT/'work/map-mobile.png'),full_page=True)
    check(not errors, 'no page errors across desktop, mobile, search, console, and authentication flows')
    print(f'Passed {checks} Chromium desktop/mobile viewing assertions.')
    print('SDK-double screenshots: work/map-desktop.png, work/map-tablet.png, work/map-mobile.png')
    browser.close()
server.shutdown()
